"""География: HMAC-смещение публичных координат датчика.

Точная координата тучки — это, как правило, адрес её владельца. Наружу отдаём
смещённую: сдвиг на 100–300 метров в случайную сторону сохраняет карту
осмысленной (район виден) и перестаёт указывать на дом.

Сдвиг **детерминированный**: одно и то же устройство всегда смещается одинаково.
Это не «недоделанная случайность», а суть механизма — случайный сдвиг на каждый
запрос усредняется обратно в истинную точку тем, кто соберёт сотню ответов.

Функция чистая, секрет приходит параметром: в окружении его пока никто не
заводит, потому что вызывать её до личного кабинета некому.
"""

import hashlib
import hmac
import math

MIN_OFFSET_M = 100.0
MAX_OFFSET_M = 300.0
# Метров в градусе широты; для долготы — то же, делённое на cos(широты).
M_PER_DEG = 111_320.0
# Округление публичной координаты: 4 знака — это ~11 м, на порядок меньше
# минимального сдвига, так что сверх самого сдвига оно ничего не скрывает
# и ничего не выдаёт.
PUBLIC_PRECISION = 4


def public_coords(device_id: int, lat: float, lon: float,
                  secret: str) -> tuple[float, float]:
    """Публичные координаты устройства: та же точка, сдвинутая на 100–300 м.

    Угол и расстояние выводятся из HMAC-SHA256(secret, device_id), так что при
    неизменном секрете результат воспроизводим, а без секрета — не предсказуем.
    """
    digest = hmac.new(secret.encode(), str(device_id).encode(),
                      hashlib.sha256).digest()
    angle = int.from_bytes(digest[:4], "big") / 2 ** 32 * 2 * math.pi
    distance = MIN_OFFSET_M + int.from_bytes(digest[4:8], "big") / 2 ** 32 * (
        MAX_OFFSET_M - MIN_OFFSET_M)

    # У полюсов cos(широты) уходит в ноль и сдвиг по долготе улетает в
    # бесконечность. Датчиков там не будет, но пусть функция остаётся
    # определённой на всём диапазоне.
    cos_lat = max(math.cos(math.radians(lat)), 0.01)
    d_lat = distance * math.cos(angle) / M_PER_DEG
    d_lon = distance * math.sin(angle) / (M_PER_DEG * cos_lat)
    return (round(lat + d_lat, PUBLIC_PRECISION),
            round(lon + d_lon, PUBLIC_PRECISION))
