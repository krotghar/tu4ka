"""Качество данных: флаги влажности, статусы датчика, FILTER-проверки.

Пока здесь только флаг влажности. Дальше сюда приедут проверки FILTER
(JRC/NILU) и специфика SDS011/BME280 — отдельной сессией.

Функции чистые и без зависимости от FastAPI: их переиспользуют API,
телеграм-бот и клиент.
"""

# SDS011 — оптический счётчик: при высокой влажности частицы набирают воду,
# растут и рассеивают свет сильнее, так что прибор завышает концентрацию.
#
# Пороги ниже привычных 85/90 намеренно. BME280 стоит в одном корпусе с
# ESP8266 и греется от него: измеренная влажность систематически ниже
# настоящей (а температура выше). То есть показанные 75% — это уже «на улице
# около 80», и отсчитывать от номинальных порогов значило бы ловить проблему
# с опозданием.
RH_SUSPECT = 75.0
RH_INVALID = 85.0


def rh_flag(humidity: float | None) -> str | None:
    """`None` | `'suspect'` | `'invalid'` по влажности.

    Только флаг: коррекцию к измерениям не применяем. Поправочные формулы
    зависят от модели датчика, его возраста и состава аэрозоля — «исправленное»
    значение выглядело бы точнее сырого, ничем этого не заслужив. Пусть
    потребитель видит измерение и оговорку к нему.
    """
    if humidity is None:
        return None
    if humidity >= RH_INVALID:
        return "invalid"
    if humidity >= RH_SUSPECT:
        return "suspect"
    return None
